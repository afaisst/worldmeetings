/*
 * Builds the holiday data used by World Meetings.
 *
 *   cd tools && npm install date-holidays && node build-holidays.js
 *
 * Writes ../data/holidays/<CC>.js (one small file per country, loaded only when
 * a time zone in that country is shown) with national public holidays — days
 * off nationwide, including substitute days — for the years below, using the
 * date-holidays package (https://github.com/commenthol/date-holidays).
 * Regional (state / canton) holidays and half-days are not included.
 */
const fs = require('fs');
const path = require('path');
const Holidays = require('date-holidays');

const FIRST_YEAR = 2025;
const LAST_YEAR = 2035;
const OUT = path.join(__dirname, '..', 'data', 'holidays');
fs.mkdirSync(OUT, { recursive: true });

const countries = Object.keys(new Holidays().getCountries());
let files = 0, entries = 0;
for (const cc of countries) {
  const hd = new Holidays(cc, { languages: ['en'] });
  const days = {};
  for (let y = FIRST_YEAR; y <= LAST_YEAR; y++) {
    for (const h of hd.getHolidays(y, 'en') || []) {
      if (h.type !== 'public') continue;
      if (!/ 00:00:00/.test(h.date)) continue;             // skip half-days (e.g. from noon)
      const span = (h.end - h.start) / 3600000;
      if (span < 20) continue;                              // must cover (almost) the whole day
      const day = h.date.slice(0, 10);
      const name = String(h.name).trim();
      if (!days[day]) days[day] = [];
      if (!days[day].includes(name)) days[day].push(name);
    }
  }
  const keys = Object.keys(days).sort();
  if (!keys.length) continue;
  const data = {};
  for (const k of keys) data[k] = days[k].join(' / ');
  entries += keys.length;
  fs.writeFileSync(path.join(OUT, cc + '.js'),
    'WMHolidays.add(' + JSON.stringify(cc) + ',' + JSON.stringify(data) + ');\n');
  files++;
}
fs.writeFileSync(path.join(OUT, 'README.md'),
  '# Holiday data\n\nNational public holidays ' + FIRST_YEAR + '–' + LAST_YEAR +
  ' per country (ISO code), generated by `tools/build-holidays.js` from the ' +
  '[date-holidays](https://github.com/commenthol/date-holidays) package (v' +
  require('date-holidays/package.json').version + '). Regenerate to extend the years.\n');
// Keep js/holidays.js's list of available countries in sync.
const hj = path.join(__dirname, '..', 'js', 'holidays.js');
const codes = fs.readdirSync(OUT).filter((f) => /^[A-Z]{2}\.js$/.test(f)).map((f) => f.slice(0, 2)).sort();
fs.writeFileSync(hj, fs.readFileSync(hj, 'utf8').replace(/new Set\('[A-Z ]*'/, "new Set('" + codes.join(' ') + "'"));
console.log('countries:', files, 'holidays:', entries);
